// Get items available in a specific zone
export function getItemsForZone(zoneId: string, items = MENU_ITEMS): MenuItem[] {
  return items.filter(item => {
    // Food items require food service capability
    if (item.category === 'food') {
      // Only show food in zones that allow it
      const foodZones = ['lounge', 'vip', 'poolside'];
      return foodZones.includes(zoneId);
    }
    // All other items available everywhere
    return true;
  });
}

